#!/usr/bin/env python3
"""Generate/check project-local Codex agent and skill adapters (Python 3.11+)."""
import argparse
import hashlib
import json
import sys
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by runtime/sync_codex.py"


def read_json(file):
    return json.loads(file.read_text(encoding="utf-8-sig"))


def safe_file(root, value):
    if not isinstance(value, str) or "\\" in value or ":" in value:
        raise ValueError("Expected a repository-relative path")
    parts = value.split("/")
    if any(part in ("", ".", "..") for part in parts):
        raise ValueError("Unsafe source path")
    file = root.joinpath(*parts).resolve()
    if not file.is_relative_to(root.resolve()):
        raise ValueError("Path escaped repository")
    return file


def read_context_settings(root):
    """Read narrow context/feature overrides; absence preserves legacy output."""
    file = safe_file(root, "runtime/codex-settings.toml")
    if not file.exists():
        return {}
    settings = tomllib.loads(file.read_text(encoding="utf-8-sig"))
    allowed = ("model", "model_context_window", "model_auto_compact_token_limit")
    unknown = set(settings) - set(allowed) - {"features"}
    if unknown:
        raise ValueError("Unsupported context setting: " + ", ".join(sorted(unknown)))
    if "model" in settings and (not isinstance(settings["model"], str) or not settings["model"].strip()):
        raise ValueError("model must be a nonempty string")
    for name in ("model_context_window", "model_auto_compact_token_limit"):
        if name in settings and (type(settings[name]) is not int or settings[name] <= 0):
            raise ValueError(f"{name} must be a positive integer")
    compact = settings.get("model_auto_compact_token_limit")
    window = settings.get("model_context_window")
    if compact is not None and (window is None or compact >= window):
        raise ValueError("model_auto_compact_token_limit requires and must be below model_context_window")
    features = settings.get("features", {})
    if not isinstance(features, dict):
        raise ValueError("features must be a table")
    unknown_features = set(features) - {"context_management"}
    if unknown_features:
        raise ValueError("Unsupported feature: " + ", ".join(sorted(unknown_features)))
    if "context_management" in features and type(features["context_management"]) is not bool:
        raise ValueError("features.context_management must be a boolean")
    result = {name: settings[name] for name in allowed if name in settings}
    if features:
        result["features"] = features
    return result


def render(root=ROOT, hook_python=None):
    registry = read_json(root / "registry.json")
    inventory = read_json(root / "shared/skills/skills.json")
    files, agents = {}, []
    context = read_context_settings(root)
    features = context.pop("features", {})
    config = [MARKER, ("# Project scope. Permissions and MCP inherit; model is project-local."
                       if "model" in context else "# Project scope. Model, permissions and MCP inherit from the parent."), ""]
    if context:
        config += ["# Source: runtime/codex-settings.toml"]
        config += [f"{name} = {json.dumps(value) if isinstance(value, str) else value}" for name, value in context.items()]
        config += [""]
    if features:
        config += ["[features]"]
        config += [f"{name} = {str(value).lower()}" for name, value in features.items()]
        config += [""]
    config += ["[agents]", "enabled = true", ""]
    for entry in registry["modules"]:
        if not entry["enabled"]:
            continue
        module = read_json(safe_file(root, entry["path"]))
        body = safe_file(root, module["instructions"]).read_text(encoding="utf-8")
        # Role snapshots retain the complete source. Inject only its unconditional entry.
        body = body.partition("\n<!-- conditional-procedures -->\n")[0]
        instructions = (
            f"You are {module['name']} ({module['id']}).\n"
            "Resolve paths against the framework root containing registry.json and runtime/agentctl.py.\n"
            f"Sources: {entry['path']} and {module['instructions']}.\n"
            "Follow the parent session and user authorization. Manifest scope does not grant OS permissions.\n"
            "Delegated agents must stay within their assignment and must not delegate further without explicit parent authorization.\n\n"
            + body
        )
        quote = lambda text: json.dumps(text, ensure_ascii=False)
        content = (MARKER + f"\n# Source: {entry['path']} @ {module['version']}\n"
                   + f"name = {quote(module['id'])}\n"
                   + f"description = {quote(module['description'])}\n"
                   + f"developer_instructions = {quote(instructions)}\n")
        parsed = tomllib.loads(content)
        assert parsed["name"] == module["id"] and parsed["developer_instructions"] == instructions
        files[f".codex/agents/{module['id']}.toml"] = content
        config += [f"[agents.{module['id']}]",
                   f"description = {quote(module['description'])}",
                   f"config_file = {quote('agents/' + module['id'] + '.toml')}", ""]
        agents.append(module["id"])
    files[".codex/config.toml"] = "\n".join(config)
    tomllib.loads(files[".codex/config.toml"])
    for skill in inventory["skills"]:
        source = safe_file(root, skill["path"]).read_text(encoding="utf-8")
        name = next(line for line in source.splitlines() if line.startswith("name: "))
        description = next(line for line in source.splitlines() if line.startswith("description: "))[13:].strip()
        if name[6:].strip() != skill["id"]:
            raise ValueError("Skill ID mismatch")
        files[f".agents/skills/{skill['id']}/SKILL.md"] = (
            "---\n" + name + "\ndescription: " + json.dumps(description, ensure_ascii=False)
            + "\n---\n\n# " + skill["id"] + "\n\n"
            + f"Source instructions: {skill['path']} (version {skill['version']}).\n\n"
            + "Locate the framework root containing registry.json and runtime/agentctl.py. "
            + f"Read {skill['path']} from that root and apply it to this task. "
            + "This is a discovery adapter. Read the source instead of recursively invoking this skill.\n"
        )
    hook_source = root / "runtime/context-hooks.json"
    if hook_source.exists():
        hook_text = hook_source.read_text(encoding="utf-8-sig")
        # Expand path values before JSON parsing; quotes/backslashes remain JSON-safe.
        hook_text = hook_text.replace("{python}", json.dumps(hook_python or sys.executable)[1:-1])
        hook_text = hook_text.replace("{root}", json.dumps(str(root.resolve()).replace(chr(92), "/"))[1:-1])
        hooks = json.loads(hook_text)
        if set(hooks.get("hooks", {})) != {"PostToolUse"}:
            raise ValueError("Context hooks must declare only PostToolUse")
        files[".codex/hooks.json"] = json.dumps(hooks, ensure_ascii=False, indent=2) + "\n"
    return files, agents, [skill["id"] for skill in inventory["skills"]]


def synchronize(root=ROOT, write=False):
    hook_name = ".codex/hooks.json"
    hook_file = safe_file(root, hook_name)
    receipt_path = safe_file(root, "work/codex-hook-install.json")
    receipt = read_json(receipt_path) if receipt_path.is_file() else {}
    # A local installation records the exact bytes and interpreter used by --write.
    # Never execute a path read from a receipt. Re-render the full command and structure.
    installed = bool(hook_file.is_file() and receipt.get("sha256") ==
                     hashlib.sha256(hook_file.read_bytes()).hexdigest())
    interpreter = receipt.get("python") if installed else None
    if interpreter and not (Path(interpreter).is_absolute() and Path(interpreter).is_file()):
        raise ValueError("Installed hook interpreter unavailable; review local installation")
    files, agents, skills = render(root, interpreter)
    state_path = root / "runtime/native-map.json"
    old = read_json(state_path).get("files", {}) if state_path.exists() else {}
    retired = sorted(set(old) - set(files))
    if write and retired:
        raise ValueError("Retired adapters require review and explicit removal: " + ", ".join(retired))
    missing, changed = [], list(retired)
    hook_ready = None
    for name, content in files.items():
        file = safe_file(root, name)
        if name == hook_name:
            hook_ready = file.is_file() and file.read_text(encoding="utf-8") == content
            if not file.exists():
                continue  # Fresh clone: tracked adapters and local activation are separate.
        if not file.exists():
            missing.append(name)
        elif file.read_text(encoding="utf-8") != content:
            changed.append(name)
            if write:
                prior_hash = old.get(name)
                if name == hook_name:
                    template_text = (root / "runtime/context-hooks.json").read_text(encoding="utf-8-sig")
                    if prior_hash == hashlib.sha256(template_text.encode("utf-8")).hexdigest():
                        prior_hash = None  # Portable template hashes do not attest installed bytes.
                prior_bytes = hashlib.sha256(file.read_bytes()).hexdigest() == prior_hash
                if not (prior_bytes or (name == hook_name and installed)):
                    raise ValueError(f"Manual change detected; review {name} before replacement")
    hashes = {name: hashlib.sha256(content.encode("utf-8")).hexdigest()
              for name, content in files.items()}
    if hook_name in files:
        template = (root / "runtime/context-hooks.json").read_text(encoding="utf-8-sig")
        hashes[hook_name] = hashlib.sha256(template.encode("utf-8")).hexdigest()
    if hook_name in files and (write or hook_file.exists()):
        if not safe_file(root, "runtime/context_checkpoint.py").is_file():
            if write:
                raise ValueError("Context hook target is missing")
            hook_ready = False
            changed.append("runtime/context_checkpoint.py")
    if write:
        for name, content in files.items():
            file = safe_file(root, name)
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content, encoding="utf-8", newline="\n")
        if hook_name in files:
            receipt_path.parent.mkdir(parents=True, exist_ok=True)
            receipt_path.write_text(json.dumps({"python": interpreter or sys.executable,
                                                "sha256": hashlib.sha256(hook_file.read_bytes()).hexdigest()}),
                                    encoding="utf-8", newline="\n")
            hook_ready = True
        state_path.write_text(json.dumps({
            "schema_version": "1.0.0", "agents": agents, "skills": skills,
            "files": hashes
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
        missing, changed = [], []
    elif old != hashes:
        changed.append("runtime/native-map.json")
    return {"local_hook_ready": hook_ready, "ok": not missing and not changed, "agents": agents, "skills": skills,
            "missing": missing, "changed": changed}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--write", action="store_true")
    args = parser.parse_args()
    result = synchronize(write=args.write)
    print(json.dumps(result, ensure_ascii=False))
    raise SystemExit(0 if result["ok"] else 1)
